/**
 * راه‌اندازی محیط برای تست‌ها (Vitest setupFiles).
 *
 * چرا لازم است؟ `src/lib/env.ts` هنگام import، `DATABASE_URL` را اجباری می‌کند و در
 * نبودش throw می‌کند. هر ماژول سمت‌سرور که گذرا `@/lib/env` را بکشد (مثل گیت‌وی
 * هوش مصنوعی) بدون این مقدار، در زمان import تست می‌افتد. این فایل پیش از اجرای
 * تست‌ها یک محیطِ تمیز و خودبسنده تأمین می‌کند تا تست‌ها «بدون شبکه و بدون دیتابیس
 * زنده» (طبق قاعده‌ی پروژه) اجرا شوند.
 *
 * عمداً `.env.local` را بار نمی‌کنیم: تست‌ها نباید به محیطِ خاصِ توسعه‌دهنده وابسته
 * باشند و گیت‌وی/شبکه را خودشان mock می‌کنند. فقط حداقلِ لازم تأمین می‌شود:
 *   • DATABASE_URL ساختگی (هرگز به DB واقعی وصل نمی‌شود).
 *   • متغیرهای اختیاریِ ONEXAI_* اگر «رشته‌ی خالی» بودند پاک می‌شوند تا با معنای
 *     «تنظیم‌نشده» (undefined) یکی شوند؛ چون اسکیمای env رشته‌ی خالی را نامعتبر می‌داند
 *     و این باعث می‌شد بوتِ env در تست بیفتد.
 */

// رشته‌ی خالیِ متغیرهای اختیاری ⇒ تنظیم‌نشده (هم‌معنا با غیاب کامل).
for (const key of ["ONEXAI_BASE_URL", "ONEXAI_API_KEY", "ONEXAI_MODEL"] as const) {
  if (process.env[key] !== undefined && process.env[key]!.trim() === "") {
    delete process.env[key];
  }
}

// مقدار پیش‌فرضِ ساختگی برای DATABASE_URL در صورت نبودن (اتصالی باز نمی‌شود).
process.env.DATABASE_URL ||= "postgres://karjoo:karjoo@localhost:5432/karjoo_test";
