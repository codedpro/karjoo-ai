import type { ChatMessage } from "@/lib/ai/gateway";

/** سقفِ طولِ متنِ رزومه که به مدل می‌دهیم (تا پرامپت بیش از حد بزرگ/گران نشود). */
export const MAX_RESUME_CHARS = 12_000;

/** متنِ بلندِ رزومه را برای تزریق در پرامپت کوتاه می‌کند (با نشانه‌ی برش). */
export function clampResumeText(text: string, max: number = MAX_RESUME_CHARS): string {
  const t = text.trim();
  return t.length > max ? `${t.slice(0, max)}…` : t;
}

