/**
 * پرامپتِ ساخت‌یافته‌سازیِ رزومه: پیام‌های system + user را برای فراخوانیِ JSON می‌سازد.
 * خروجیِ موردانتظارِ مدل با `parsedResumeSchema` (schema.ts) اعتبارسنجی می‌شود.
 *
 * @param resumeText متنِ خامِ استخراج‌شده‌ی رزومه (از pdf util).
 */
export function buildResumeParsePrompt(resumeText: string): ChatMessage[] {
  const user = [
    "متنِ خامِ رزومه (بینِ سه‌خط‌تیره):",
    "---",
    clampResumeText(resumeText),
    "---",
    "فیلدهای ساخت‌یافته را طبقِ ساختارِ خواسته‌شده استخراج کن و فقط همان JSON را برگردان.",
  ].join("\n");

  return [
    { role: "system", content: SYSTEM },
    { role: "user", content: user },
  ];
}
