/**
 * اسکیماهای zod برای ورودیِ خارجیِ مسیرهای علاقه‌مندی/دسته‌بندی (Track B).
 *
 * هر چیزی که از کلاینت می‌آید پیش از لمسِ DB اینجا اعتبارسنجی می‌شود. نکته‌ی امنیتی
 * (قاعده‌ی §10 — داده‌ی هر کاربر فقط برای همان کاربر): این بدنه عمداً `userId` نمی‌گیرد؛
 * کاربرِ هدف فقط از نشستِ احرازشده گرفته می‌شود، نه از بدنه‌ی قابلِ دستکاری.
 */
import { z } from "zod";

/**
 * بدنه‌ی PUT /api/interests — جایگزینیِ کاملِ مجموعه‌ی دسته‌های انتخابیِ کاربر.
 *
 * با slug کار می‌کنیم (نه UUIDِ ردیف): slug پایدار و مستقل از DB است و کلاینت همان را
 * از GET /api/categories دارد. آرایه‌ی خالی = پاک‌کردنِ همه‌ی علاقه‌مندی‌ها (مجاز).
 * سقفِ طول برای جلوگیری از بدنه‌ی غول‌آسا؛ نامعتبر/ناشناخته در route فیلتر می‌شود.
 */
export const updateInterestsBodySchema = z.object({
  /** slugِ دسته‌های انتخابی (kebab-case). یکتاسازی/اعتبارِ تاکسونومی در route. */
  slugs: z
    .array(
      z
        .string()
        .trim()
        .min(1, "slug نباید خالی باشد")
        .max(80, "slug بیش از حد بلند است"),
    )
    .max(64, "تعدادِ دسته‌ها بیش از حد مجاز است"),
});

export type UpdateInterestsBody = z.infer<typeof updateInterestsBodySchema>;
